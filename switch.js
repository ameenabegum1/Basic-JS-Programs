let num1=2
let num2=3
let operator="-"    
switch(operator){
    case "+":
        console.log(num1+num2);     
        break;
    case "-":
        console.log(num1-num2);     
        break;      
    case "*":
        console.log(num1*num2);     
        break;
    case "/":
        console.log(num1/num2);
        break;
}